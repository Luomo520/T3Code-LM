/** One source for future builds; never operates on already delivered artifacts. */
import * as NodeFS from "node:fs";
import * as NodePath from "node:path";
import * as NodeURL from "node:url";
const root = NodePath.dirname(NodePath.dirname(NodeURL.fileURLToPath(import.meta.url)));
const config = JSON.parse(
  NodeFS.readFileSync(NodePath.join(root, "scripts/fork-release.json"), "utf8"),
);
if (
  !/^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)$/.test(config.productVersion) ||
  !Number.isSafeInteger(config.build) ||
  config.build < 1 ||
  !Number.isSafeInteger(config.androidVersionCode) ||
  config.androidVersionCode < 35 ||
  config.repository !== "Luomo520/T3Code-LM" ||
  config.channel !== "release"
) {
  throw new Error("Invalid fork release identity or non-monotonic Android baseline");
}
const version = `${config.productVersion}-${config.build}`;
const generated = `// Generated by scripts/sync-fork-version.mjs from scripts/fork-release.json.\nexport const FORK_RELEASE_REPOSITORY = ${JSON.stringify(config.repository)};\nexport const FORK_RELEASE_VERSION = ${JSON.stringify(version)};\nexport const FORK_ANDROID_VERSION_CODE = ${config.androidVersionCode};\nexport const FORK_RELEASE_MANIFEST_FILE = "T3Code-LM-release.json";\nexport const FORK_RELEASE_FEED_URL = "https://github.com/${config.repository}/releases/latest/download";\n`;
const files = new Map([["packages/shared/src/forkRelease.generated.ts", generated]]);
for (const rel of [
  "apps/server/package.json",
  "apps/desktop/package.json",
  "apps/web/package.json",
  "apps/mobile/package.json",
]) {
  const value = JSON.parse(NodeFS.readFileSync(NodePath.join(root, rel), "utf8"));
  value.version = version;
  files.set(rel, JSON.stringify(value, null, 2) + "\n");
}
const check = process.argv.includes("--check");
const stale = [...files].filter(([rel, value]) => {
  const file = NodePath.join(root, rel);
  return !NodeFS.existsSync(file) || NodeFS.readFileSync(file, "utf8") !== value;
});
if (check && stale.length)
  throw new Error(`Version metadata is stale: ${stale.map(([rel]) => rel).join(", ")}`);
if (!check) for (const [rel, value] of stale) NodeFS.writeFileSync(NodePath.join(root, rel), value);
console.log(
  `${check ? "Verified" : "Synchronized"} ${config.product} ${version} (${stale.length} files)`,
);
